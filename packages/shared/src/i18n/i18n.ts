export function isValidLocale(locale: string): locale is LocaleCode {
  return SUPPORTED_LOCALES.includes(locale as LocaleCode);
}

export function getLocaleDirection(locale: LocaleCode): 'ltr' | 'rtl' {
  return LOCALE_NAMES[locale].rtl ? 'rtl' : 'ltr';
}

export function getLocaleName(locale: LocaleCode, inNative = false): string {
  return inNative ? LOCALE_NAMES[locale].native : LOCALE_NAMES[locale].english;
}

export function getLocaleFlag(locale: LocaleCode): string {
  return LOCALE_FLAGS[locale];
}

export function getLocaleFromHeader(acceptLanguage: string): LocaleCode {
  const langs = acceptLanguage
    .split(',')
    .map(l => l.split(';')[0].trim().toLowerCase())
    .map(l => l.split('-')[0]);

  for (const lang of langs) {
    if (SUPPORTED_LOCALES.includes(lang as LocaleCode)) {
      return lang as LocaleCode;
    }
  }
  return DEFAULT_LOCALE;
}

export function getLocaleFromPath(pathname: string): LocaleCode | null {
  const match = pathname.match(/^\/([a-z]{2}(?:-[A-Z]{2})?)(?:\/|$)/);
  if (match && isValidLocale(match[1])) {
    return match[1];
  }
  return null;
}

export function addLocaleToPath(path: string, locale: LocaleCode): string {
  const cleanPath = path.replace(/^\/[a-z]{2}(?:-[A-Z]{2})?(?=\/|$)/, '');
  return `/${locale}${cleanPath === '/' ? '' : cleanPath}`;
}

export function removeLocaleFromPath(path: string): string {
  return path.replace(/^\/[a-z]{2}(?:-[A-Z]{2})?(?=\/|$)/, '') || '/';
}

export function buildTranslationKey(namespace: string, key: string): string {
  return `${namespace}.${key}`;
}

export function parseTranslationKey(fullKey: string): { namespace: string; key: string } | null {
  const dotIndex = fullKey.indexOf('.');
  if (dotIndex === -1) return null;
  return {
    namespace: fullKey.slice(0, dotIndex),
    key: fullKey.slice(dotIndex + 1)
  };
}

export function flattenTranslations(translations: Translation[]): TranslationNamespace {
  const result: TranslationNamespace = {};

  for (const t of translations) {
    const keys = t.key.split('.');
    let current: Record<string, unknown> = result;

    for (let i = 0; i < keys.length - 1; i++) {
      if (!current[keys[i]]) current[keys[i]] = {};
      current = current[keys[i]] as Record<string, unknown>;
    }

    current[keys[keys.length - 1]] = t.value;
  }

  return result;
}

export function unflattenTranslations(
  namespace: string,
  localeId: string,
  tenantId: string | undefined,
  translations: TranslationNamespace
): Translation[] {
  const result: Translation[] = [];

  function traverse(obj: Record<string, unknown>, prefix = ''): void {
    for (const [key, value] of Object.entries(obj)) {
      const fullKey = prefix ? `${prefix}.${key}` : key;
      if (typeof value === 'string') {
        result.push({
          id: '', // Will be generated by DB
          namespace,
          key: fullKey,
          value,
          localeId,
          tenantId,
          context: undefined,
          isReviewed: false,
          createdAt: new Date(),
          updatedAt: new Date()
        });
      } else if (typeof value === 'object' && value !== null) {
        traverse(value as Record<string, unknown>, fullKey);
      }
    }
  }

  traverse(translations);
  return result;
}

